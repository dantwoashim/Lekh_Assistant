async function freezeBlind() {
  const out = createWriter(path.join(CURATED_DIR, CURATED_FILES.d8));
  const blindKeys = new Set();
  let count = 0;
  for await (const row of readJsonl(generatedPath("d8"))) {
    const normalized = normalizeBlind(row);
    if (!normalized) continue;
    if (hasBlockedCorpusTrace(normalized)) continue;
    blindKeys.add(normalized.holdoutKey);
    out.write(normalized);
    count += 1;
  }
  out.close();
  counters.d8 = count;
  return blindKeys;
}

async function curateDataset(key, blindKeys, normalizer) {
  const out = createWriter(path.join(CURATED_DIR, CURATED_FILES[key]));
  const seen = new Set();
  let count = 0;
  let dropped = 0;
  for await (const row of readJsonl(generatedPath(key))) {
    const normalized = normalizer(row);
    if (!normalized) {
      dropped += 1;
      continue;
    }
    if (hasBlockedCorpusTrace(normalized)) {
      dropped += 1;
      continue;
    }
    if (seen.has(normalized.dedupeKey)) {
      dropped += 1;
      continue;
    }
    seen.add(normalized.dedupeKey);
    normalized.split = blindKeys.has(normalized.holdoutKey) ? "blind_holdout" : "train";
    if (normalized.split === "blind_holdout") leakage.heldOutRows += 1;
    else leakage.checkedTrainRows += 1;
    delete normalized.dedupeKey;
    delete normalized.holdoutKey;
    out.write(normalized);
    collectRuntimeCandidate(key, normalized);
    collectReviewCandidate(key, normalized);
    count += 1;
  }
  out.close();
  counters[key] = count;
  counters[`${key}Dropped`] = dropped;
}

