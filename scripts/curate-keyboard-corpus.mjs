function countQualityLabels() {
  const counts = { gold: 0, silver: 0, bronze: 0, synthetic: 0, blind: counters.d8 ?? 0 };
  for (const row of [...runtime.words, ...runtime.phrases, ...runtime.proofread, ...runtime.names, ...runtime.contexts]) {
    if (row.quality in counts) counts[row.quality] += 1;
  }
  return counts;
}

function buildPrefixPack(rows, key) {
  const prefixIndex = {};
  for (const row of rows) {
    const value = String(row[key] ?? "").toLowerCase();
    for (let i = 1; i <= Math.min(8, value.length); i += 1) {
      const prefix = value.slice(0, i);
      const bucket = prefixIndex[prefix] ?? [];
      if (bucket.length < 12) bucket.push(row);
      prefixIndex[prefix] = bucket;
    }
  }
  return { version: "v0.1", rows, prefixIndex };
}

function qualityFor(reviewStatus) {
  if (reviewStatus === "project-internal-seed") return "gold";
  if (reviewStatus === "synthetic-silver") return "synthetic";
  if (reviewStatus === "pii-screened-open-social") return "bronze";
  if (String(reviewStatus || "").includes("ngram")) return "silver";
  if (String(reviewStatus || "").includes("auto-reviewed")) return "silver";
  return "bronze";
}

