async function* readJsonl(file) {
  const rl = readline.createInterface({
    input: fs.createReadStream(file, "utf8"),
    crlfDelay: Infinity,
  });
  for await (const line of rl) {
    if (!line.trim()) continue;
    yield JSON.parse(line);
  }
}

function createWriter(file) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const stream = fs.createWriteStream(file, "utf8");
  return {
    write(row) {
      stream.write(`${JSON.stringify(row)}\n`);
    },
    close() {
      stream.end();
    },
  };
}

function writeJsonl(file, rows) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${rows.map((row) => JSON.stringify(row)).join("\n")}\n`);
}

function writeJson(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

function normalizeRoman(value) {
  return String(value || "")
    .normalize("NFKC")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9' -]/g, "")
    .replace(/\s+/g, " ");
}

function normalizePhrase(value) {
  return String(value || "")
    .normalize("NFKC")
    .trim()
    .replace(/[^\p{L}\p{M}\p{N}' ._-]+/gu, " ")
    .replace(/\s+/g, " ");
}

function normalizeRomanSentence(value) {
  const text = String(value || "")
    .normalize("NFKC")
    .replace(/https?:\/\/\S+|www\.\S+/gi, " ")
    .replace(/[\w.+-]+@[\w.-]+\.[a-z]{2,}/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
  return /[A-Za-z]/.test(text) ? text : "";
}

function normalizeMixed(value) {
  return String(value || "")
    .normalize("NFKC")
    .replace(/https?:\/\/\S+|www\.\S+/gi, " ")
    .replace(/[\w.+-]+@[\w.-]+\.[a-z]{2,}/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function normalizeUnicode(value) {
  return String(value || "").normalize("NFC").trim().replace(/\s+/g, " ");
}

function normalizeUnicodeCandidates(value) {
  return uniqueStrings(Array.isArray(value) ? value.map(normalizeUnicode) : [normalizeUnicode(value)]).filter((item) => /[\u0900-\u097F]/.test(item));
}

function uniqueStrings(value) {
  return Array.from(new Set((Array.isArray(value) ? value : []).map((item) => String(item || "").trim()).filter(Boolean)));
}

function clamp(value) {
  const number = Number(value);
  if (!Number.isFinite(number)) return 0;
  return Math.max(0, Math.min(1, number));
}

function hash(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}
