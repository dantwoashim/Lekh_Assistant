function blindHoldoutKey(task, payload) {
  if (task === "romanized-to-unicode-word") {
    return `romanized-to-unicode-word:${normalizeRoman(payload.romanized)}:${normalizeUnicodeCandidates(payload.expected).join("|")}`;
  }
  if (task === "romanized-to-unicode-phrase") {
    return `romanized-to-unicode-phrase:${normalizePhrase(payload.romanized)}:${normalizeUnicodeCandidates(payload.expected).join("|")}`;
  }
  if (task === "casual-romanized-preserve-or-suggest") {
    return `casual-romanized-preserve-or-suggest:${normalizeRomanSentence(payload.input)}`;
  }
  if (task === "mixed-nepali-english-policy") {
    return `mixed-nepali-english-policy:${normalizeMixed(payload.input)}`;
  }
  if (task === "proofread-correction") {
    return `proofread-correction:${normalizeUnicode(payload.error)}:${normalizeUnicode(payload.correction)}:${payload.type ?? ""}`;
  }
  if (task === "name-variant-candidate") {
    return `name-variant-candidate:${normalizePhrase(payload.romanized)}:${normalizeUnicodeCandidates(payload.expected).join("|")}`;
  }
  if (task === "next-word-context") {
    return `next-word-context:${normalizePhrase(payload.context)}:${normalizePhrase(payload.next)}`;
  }
  return undefined;
}

function collectRuntimeCandidate(key, row) {
  if (row.split !== "train") return;
  const runtimeText = [row.romanized, row.context, row.next, ...(row.unicodeCandidates ?? [])].filter(Boolean).join(" ");
  if (hasBlockedRuntimeTrace(runtimeText, { includeContextTerms: key === "d7" })) return;
  if (key === "d1" && row.quality !== "bronze" && runtime.words.length < 25_000) {
    runtime.words.push({
      romanized: row.romanized,
      unicode: row.unicodeCandidates[0],
      confidence: row.confidence,
      quality: row.quality,
    });
  }
  if (key === "d2" && ["gold", "silver"].includes(row.quality) && runtime.phrases.length < 10_000) {
    runtime.phrases.push({
      romanized: row.romanized,
      unicode: row.unicodeCandidates[0],
      domain: row.domain,
      confidence: row.confidence,
      quality: row.quality,
    });
  }
  if (key === "d4") {
    for (const token of row.preserveTokens ?? []) {
      if (!hasBlockedRuntimeTrace(token, { includeContextTerms: true })) runtime.mixedPolicy.preserveAlways.add(token);
    }
    for (const token of row.preferenceTokens ?? []) {
      if (!hasBlockedRuntimeTrace(token, { includeContextTerms: true })) runtime.mixedPolicy.preferenceTokens.add(token);
    }
  }
  if (key === "d5" && runtime.proofread.length < 5_000) {
    runtime.proofread.push({
      error: row.error,
      correction: row.correction,
      type: row.type,
      confidence: row.confidence,
      quality: row.quality,
    });
  }
  if (key === "d6" && runtime.names.length < 5_000) {
    runtime.names.push({
      romanized: row.romanized,
      unicode: row.unicodeCandidates[0],
      subtype: row.subtype,
      confidence: row.confidence,
      quality: row.quality,
    });
  }
  if (key === "d7" && row.quality !== "synthetic" && runtime.contexts.length < 20_000) {
    runtime.contexts.push({
      context: row.context,
      next: row.next,
      confidence: row.confidence,
      quality: row.quality,
    });
  }
}

function hasBlockedRuntimeTrace(value, { includeContextTerms = false } = {}) {
  const text = normalizePhrase(value).toLowerCase();
  if (!text) return false;
  if (BLOCKED_TRACE_PHRASES.some((phrase) => text.includes(phrase))) return true;
  const tokens = text.match(/[a-z0-9]+/g) ?? [];
  return tokens.some(
    (token) =>
      [...BLOCKED_RUNTIME_TRACE_TERMS].some((term) => token.includes(term)) ||
      (includeContextTerms && BLOCKED_CONTEXT_TRACE_TERMS.has(token))
  );
}

function hasBlockedCorpusTrace(row) {
  const values = [];
  collectStringValues(row, values, new Set());
  return values.some((value) => hasBlockedRuntimeTrace(value));
}

function collectStringValues(value, values, seen) {
  if (value == null) return;
  if (typeof value === "string") {
    values.push(value);
    return;
  }
  if (typeof value !== "object") return;
  if (seen.has(value)) return;
  seen.add(value);
  if (Array.isArray(value)) {
    for (const item of value) collectStringValues(item, values, seen);
    return;
  }
  for (const item of Object.values(value)) collectStringValues(item, values, seen);
}

function collectReviewCandidate(key, row) {
  if (queue.length >= 25_000) return;
  if (hasBlockedCorpusTrace(row)) return;
  const highImpact =
    row.quality === "bronze" ||
    (row.quality === "synthetic" && ["d5", "d6"].includes(key)) ||
    (row.confidence != null && row.confidence < 0.7);
  if (!highImpact) return;
  queue.push({
    queueId: `review_${String(queue.length + 1).padStart(7, "0")}`,
    dataset: row.dataset,
    rowId: row.id,
    priority: row.quality === "bronze" ? "P1" : "P2",
    reason: row.quality === "bronze" ? "public/social row needs human quality and privacy review" : "synthetic or low-confidence row needs promotion decision",
    task: reviewTaskFor(key),
    qualityBefore: row.quality,
    suggestedAction: row.quality === "bronze" ? "review-license-privacy-and-conversion" : "accept-edit-or-reject",
    row,
  });
}

